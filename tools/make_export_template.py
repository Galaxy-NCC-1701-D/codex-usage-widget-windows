"""Build the native exporter's default slide-master/layout parts. Dev only; no Python needed by the app."""
from pptx import Presentation
from io import BytesIO
from zipfile import ZipFile
from pathlib import Path
p=Presentation();p.slide_width=12192000;p.slide_height=6858000
b=BytesIO();p.save(b)
items=[]
for name in ZipFile(b).namelist():
 if name.endswith('.xml') or name.endswith('.rels'):
  data=ZipFile(b).read(name).decode('utf-8');items.append((name,data))
 else:items.append((name,ZipFile(b).read(name)))
out=['#pragma once','// Generated by tools/make_export_template.py; default Office XML master/layout parts.','inline std::vector<std::pair<std::string,std::string>> slideTemplate(){return {']
for name,data in items:
 if isinstance(data,str):out.append('{"'+name+'",R"UWXML('+data+')UWXML"},')
 else:out.append('{"'+name+'",std::string("'+''.join('\\x%02x'%v for v in data)+'",'+str(len(data))+')},')
out.append('};}')
Path(__file__).resolve().parents[1].joinpath('src/slide_template.hpp').write_text('\n'.join(out))
print(len(items),'parts,',sum(len(d) for n,d in items),'bytes')
